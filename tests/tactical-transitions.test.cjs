'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const T=require('../js/tactical-transitions.js'),Brain=require('../js/race-brain.js');
const line=[1,2,3,4],order=[1,2,3,4,5,6,7,8,9],lineup=[[1,2,3,4],[5,6],[7],[8,9]];
const broken=T.splitLine(line,'breaks');
assert.deepEqual(broken.segments,[[1],[2,3,4]]);
assert.deepEqual(broken.edges.map(e=>e.status),['breaks','not_observed','not_observed']);
assert.deepEqual(T.gapReorder(order,line,1),order,'a gap cannot reorder all the following riders');
const p=new Map([[5,{seat:.95,ex_tobitsuki_delta:.025}],[6,{seat:.95}]]);
const missing=T.gapBranches({order,lineup,controller:1,gap:'breaks',profile:p,tactic:'kamashi',controllerIsAttacker:true});
assert.equal(missing.length,1);
assert.equal(missing[0].seat,null);
assert.deepEqual(missing[0].order,order);
assert.deepEqual(missing[0].links.segments,[[1],[2,3,4]]);
assert.equal(missing[0].seatState,'vacant');
const shortLine=[[1,2],[5,6],[7],[8,9],[3,4]];
const shortOrder=[1,2,5,6,7,8,9,3,4];
const opts={order:shortOrder,lineup:shortLine,controller:1,gap:'breaks',profile:p,tactic:'kamashi',controllerIsAttacker:true};
const two=T.gapBranches(opts);
assert.equal(two.length,2);
assert.equal(two[0].seat,null);
assert.deepEqual(two[0].order,shortOrder);
assert.equal(two[1].seat,5);
assert.deepEqual(two[1].order.slice(0,4),[1,5,2,6]);
assert.equal(two[1].seatState,'attempted_takeover');
assert(Math.abs(two[0].weight+two[1].weight-1)<1e-10);
assert.equal(T.gapBranches({...opts,tactic:'makuri'}).length,1);
assert.equal(T.gapBranches({...opts,controllerIsAttacker:false}).length,1);
assert.equal(T.gapBranches({...opts,order:[1,2,6,5,7,8,9,3,4]}).length,1,'second-line rider is not automatic seat challenger');
const baseline={track:.65};
const head={ex_metric_counts:{chigiri:{events:12,opportunities:24}}};
const follow={...baseline,ex_track_base:.65,track:.45,ex_metric_counts:{chigirarare:{events:6,opportunities:30}}};
const single=T.combinedBreakEvidence(head,{});
const joint=T.combinedBreakEvidence(head,follow);
assert.equal(joint.basis,'joint_ex');
assert.equal(joint.effective_n,30);
assert(joint.risk>=0&&joint.risk<=1);
const a=T.followerOutcome({leader:head,follower:follow,leaderAbility:.7,followerAbility:.65,acceleration:.22});
const b=T.followerOutcome({leader:{},follower:baseline,leaderAbility:.7,followerAbility:.65,acceleration:.22});
assert(a.keep<b.keep,'source evidence changes only the relative wheel break, not direct finish');
assert(a.keep>.18);
assert.equal(T.combinedBreakEvidence({},{}).basis,'no_EX');
const sample=JSON.parse(fs.readFileSync('race_sample.json','utf8'));
const old=Brain.build(sample);
const modern=Brain.build(sample,{transitionMode:'physical_v2'});
assert.equal(modern.chosen.length,20);
assert(modern.narratives.length>0);
assert(modern.narratives.every(n=>n.snapshots.length===5&&new Set(n.trio).size===3));
assert(modern.narratives.every(n=>n.mode!=='seat'||n.seat_state==='attempted_takeover'),'no unverified seat filling');
assert(modern.narratives.every(n=>n.snapshots[2].wheel_links&&Array.isArray(n.snapshots[2].wheel_links)));
assert(modern.narratives.every(n=>n.mode!=='recovery'),'third does not automatically lose its own wheel when marker loses leader');
const allSeats=modern.narratives.filter(n=>n.mode==='seat');
assert(allSeats.length>0,'genuine two-car close approach keeps a seat scenario alive');
assert(old.narratives.some(n=>n.mode==='recovery'),'legacy is still available for matched comparisons');
const seven=structuredClone(sample);
seven.riders=seven.riders.slice(0,7);
seven.lineup=seven.lineup.map(l=>l.filter(no=>seven.riders.some(x=>x.no===no))).filter(l=>l.length);
const sevenV2=Brain.build(seven,{transitionMode:'physical_v2'});
assert.equal(sevenV2.chosen.length,20);
console.log('EX_TACTICAL_V2_TESTS_OK '+JSON.stringify({
 baseline_paths:old.narratives.length,physical_paths:modern.narratives.length,
 v2_seat_paths:allSeats.length,seven_paths:sevenV2.narratives.length,
 no_teleport:true,nonindependent_ex:true,legacy_comparison:true}));
