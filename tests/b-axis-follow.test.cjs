'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const B=require('../js/b-axis/engine.js'),Input=require('../js/line/input.js'),Follow=require('../js/b-axis/follow.js');
const stored=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/lab_history/2026-11-08/p-285d0fbf519331a2e7b754f5e1f170800bb5e59136242d5baadd866d73b0c059.json'),'utf8'));
assert(stored.pre_race===true);
const input=Input.prepare(stored.input,{},Date.parse(stored.saved_at)),race=input.race;
assert.equal(race.venue,'四日市');assert.equal(race.race_no,12);
assert.deepEqual(race.lineup.find(l=>l.includes(5)),[8,3,5]);
const c=race.riders.find(r=>r.no===5),t=race.riders.find(r=>r.no===3);
assert(c.score>t.score,'Kosei above Terasaki in competition score for fixed pre-race snapshot');
const cProfile=Follow.profile(input.features,c,t,{fast:false,date:race.date});
assert(cProfile.tracking>.58,'stronger third-wheel rider must not inherit neutral .55 blindly');
assert.equal(cProfile.followTarget,3);
assert.equal(cProfile.status,'following');
function check(s,expectedFollow=3){
 const x=s.b.states.find(x=>x.no===5),ahead=s.b.states.find(x=>x.no===expectedFollow);
 assert.equal(x.followTarget,expectedFollow,'third wheel must be evaluated against preceding rider, not B-front globally');
 assert(x.wheelGap!==null&&x.wheelGap<1.11,'no artificial third-wheel separation when strong rider follows a strong marker');
 assert.equal(x.track,'追走');
 assert(x.gap>ahead.gap,'follower is behind preceding wheel');
 assert(Math.abs(x.gap-ahead.gap-x.wheelGap)<=.002,'cumulative gap equals adjacent wheel gap');
 assert(!s.b.phases[3].events.some(e=>e.actor===5&&e.action==='detached'));
 assert(!s.b.interactions.detachment.some(d=>d.no===5));
}
for(const tactic of ['press','hold'])check(B.build(input,{bNo:8,tactic,limit:10}));
const takeover=B.build(input,{bNo:3,tactic:'surge',limit:10});
check(takeover);
assert.deepEqual(takeover.b.phases[2].lineOrder.find(l=>l.includes(5)),[8,3,5],'at home the original line order has not been teleported');
assert.deepEqual(takeover.b.phases[3].lineOrder.find(l=>l.includes(5)),[3,5,8],'at B the original second wheel takes lead, former third immediately follows');
assert.equal(takeover.b.states.find(x=>x.no===5).role,'B番手');
assert.equal(takeover.b.phases[3].leader,3);
const outsider=B.build(input,{bNo:9,tactic:'press',limit:10});
check(outsider);
assert(outsider.b.states.find(x=>x.no===5).gap>3,'behind other B line is not the same as torn off own line');
const second=B.build(input,{bNo:3,tactic:'surge',limit:5});
assert(second.tickets.length<=5);
const archive=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/b_axis_role_history.json'),'utf8'));
assert(archive.training_end<'2026-11-08');
assert(archive.provenance.actual_b_available===false);
assert(archive.all.eligible>=1500&&archive.all.runners['9']>=100);
assert(archive.all.eligible===archive.train.eligible+archive.holdout.eligible);
const firstId=Object.keys(archive.rider_roles)[0],row=archive.rider_roles[firstId];
assert(row.n>=5);
const fakeRider={no:5,meta:{rider_id:firstId}};
assert.equal(Follow.history(archive,fakeRider,'2026-11-06'),null,'prevent lookahead from November 7 in earlier replay');
assert.equal(Follow.history(archive,fakeRider,'2026-11-08')?.n>=6,row.n>=6);
const withArchive=structuredClone(input);
withArchive.bAxisHistory=archive;
const future=B.build(withArchive,{bNo:3,tactic:'surge'});
assert(future.b.states.every(s=>Number.isFinite(s.gap)));
assert.deepEqual(future.b.states.find(s=>s.no===5).historyAssociation,{n:6,top3:4},'Kosei actual rider ID links to prior-date follower-role results');
assert.equal(future.b.states.find(s=>s.no===5).followTarget,3);
console.log('B-AXIS follow ability: Yokkaichi 8-3-5, marker launch, no bogus Kosei detachment, archive cutoff and 7/9 role data passed');
