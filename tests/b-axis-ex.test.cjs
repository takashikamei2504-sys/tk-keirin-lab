'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const Ex=require('../js/b-axis/ex-data.js'),B=require('../js/b-axis/engine.js'),Input=require('../js/line/input.js');
const saved=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/lab_history/2026-11-08/p-285d0fbf519331a2e7b754f5e1f170800bb5e59136242d5baadd866d73b0c059.json'),'utf8'));
const x=Input.prepare(saved.input,{},Date.parse(saved.saved_at));
const source='https://www.winticket.jp/keirin/cyclist/014838';
const make=(metrics)=>({source_url:source,published_at:'2026-11-06T05:00:00Z',collected_at:'2026-11-07T05:00:00Z',period_end:'2026-11-06',metrics});
const withEx=structuredClone(x);
withEx.bAxisEx={schema:'tk-b-axis-ex-observations/v1',riders:{
 '14838':make({chigirarare:{events:20,opportunities:20,rate:1},solo_win:{events:12,opportunities:20}}),
 '15413':make({chigiri:{events:20,opportunities:20},kamashi:{events:14,opportunities:18}}),
}};
const k=x.race.riders.find(r=>r.no===5),t=x.race.riders.find(r=>r.no===3);
assert.equal(Ex.identity(k),'14838');
assert.equal(Ex.identity(t),'15413');
assert.equal(Ex.evidence(withEx,k,'chigirarare',{asOf:x.as_of}).rate,1);
assert.equal(Ex.evidence(withEx,k,'solo_win',{asOf:x.as_of}).rate,.6);
assert.equal(Ex.evidence(withEx,k,'chigiri',{asOf:x.as_of}),null);
assert.equal(Ex.evidence(withEx,k,'arbitraryKey',{asOf:x.as_of}),null);
const baseline=B.build(x,{bNo:3,tactic:'surge'});
const changed=B.build(withEx,{bNo:3,tactic:'surge'});
const before=baseline.b.states.find(s=>s.no===5),after=changed.b.states.find(s=>s.no===5);
assert.equal(after.followTarget,3);
assert(after.wheelGap>before.wheelGap,'actual EX rates affect relative wheel gap');
assert.equal(after.exObservation.chigirarare.events,20);
assert.equal(after.exObservation.chigiri.events,20);
assert(changed.tickets.length>0,'valid statistics must not wipe out trifecta pool');
assert.equal(changed.b.phases[3].leader,3);
const invalid=structuredClone(withEx);
invalid.bAxisEx.riders['14838'].collected_at='2026-11-09T00:00:00Z';
assert.equal(Ex.evidence(invalid,k,'chigirarare',{asOf:x.as_of}),null,'future observations forbidden');
const badSource=structuredClone(withEx);
badSource.bAxisEx.riders['14838'].source_url='https://example.com/fictional';
assert.equal(Ex.evidence(badSource,k,'chigirarare',{asOf:x.as_of}),null,'source must be official EX path');
const noN=structuredClone(withEx);
delete noN.bAxisEx.riders['14838'].metrics.chigirarare.opportunities;
assert.equal(Ex.evidence(noN,k,'chigirarare',{asOf:x.as_of}),null,'denominator required');
const mismatch=structuredClone(withEx);
mismatch.bAxisEx.riders['14838'].metrics.chigirarare.rate=.2;
assert.equal(Ex.evidence(mismatch,k,'chigirarare',{asOf:x.as_of}),null,'reported rate and counts must agree');
const blank=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/b_axis_ex_observations.json'),'utf8'));
assert.equal(blank.schema,'tk-b-axis-ex-observations/v1');
assert.equal(Object.keys(blank.riders).length,0,'do not populate fictitious EX figures');
const archive=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/b_axis_role_history.json'),'utf8'));
assert(archive.rider_positions&&Object.keys(archive.rider_positions).length>=500);
assert(archive.all.lineSize['1'].lines>100);
const someSolo=Object.values(archive.rider_positions).find(a=>a.solo?.n>=3);
assert(someSolo&&Number.isFinite(someSolo.solo.top3));
console.log('B-AXIS EX and solo role tests passed: dated source checks, counted EX affects follower gap, no fabricated input and individual solo history');
