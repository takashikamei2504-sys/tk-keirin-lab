'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {summary,ticketCapture,validate}=require('../scripts/b_axis_oracle_backtest.cjs');
const data=JSON.parse(fs.readFileSync(path.join(__dirname,'..','research','b-axis','pilot_2026_11_06.json'),'utf8'));
const x=summary(data.races);
assert.equal(x.all.n,26);
assert.equal(x.all.b_line_head,25);
assert.equal(x.all.b_line_nonhead,1);
assert.deepEqual([x.all.b_first,x.all.b_top2,x.all.b_top3,x.all.line_wins,x.all.line_pair,x.all.line_sweep],[13,18,21,19,13,6]);
assert.deepEqual([x.seven.n,x.seven.b_first,x.seven.b_top3],[14,10,12]);
assert.deepEqual([x.nine.n,x.nine.b_first,x.nine.b_top3],[12,3,9]);
assert.equal(new Set(data.races.map(r=>r.race_id)).size,26);
assert.throws(()=>validate({...data.races[0],finish:[1,1,2]}));
const r=data.races[0];
const c=ticketCapture(data.races,{[r.race_id]:[[4,1,3],[1,4,3],[4,3,1]]});
assert.deepEqual(c['3'],{evaluated:1,hits:1});
assert.deepEqual(c['10'],{evaluated:1,hits:1});
assert.throws(()=>ticketCapture(data.races,{[r.race_id]:[[4,1,3],[4,1,3]]}));
console.log('B-AXIS oracle pilot: validation & scoring tests passed');
