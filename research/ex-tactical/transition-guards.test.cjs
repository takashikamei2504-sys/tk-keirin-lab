'use strict';
const assert=require('node:assert/strict'),T=require('./transition-guards.cjs');
const line=[1,2,3,4];
const edges=T.lineEdges(line);
assert.deepEqual(edges.map(x=>x.key),['1>2','2>3','3>4']);
const a=T.connectedSegments(line,{'1>2':'breaks','2>3':'holds','3>4':'holds'});
assert.deepEqual(a.segments,[[1],[2,3,4]]);
const b=T.connectedSegments(line,{'1>2':'holds','2>3':'breaks','3>4':'holds'});
assert.deepEqual(b.segments,[[1,2],[3,4]]);
const c=T.connectedSegments(line,{'1>2':'holds','2>3':'holds'});
assert.deepEqual(c.segments,[[1,2,3],[4]]);
assert.deepEqual(c.unknown,['3>4']);
assert.throws(()=>T.connectedSegments(line,{'2>3':'phantom'}),/INVALID_EDGE_STATE/);
const lineup=[[1,2,3,4],[5,6],[7]],order=[1,2,3,4,5,6,7];
const args={lineup,order,leader:1,candidate:5,incumbent:2,incumbentDetached:true,hasOutsideLane:true};
assert.equal(T.seatOpportunity(args).status,'unobserved','four preceding wheels cannot be crossed in one step');
assert.equal(T.seatOpportunity({...args,order:[1,2,5,3,4,6,7]}).status,'vacant_approach_possible');
assert.equal(T.seatOpportunity({...args,order:[1,2,5,3,4,6,7],incumbentDetached:false}).status,'unobserved');
assert.equal(T.seatOpportunity({...args,order:[1,2,5,3,4,6,7],incumbentDetached:false,documentedContested:true}).status,'contested_attempt_possible');
assert.equal(T.seatOpportunity({...args,order:[1,2,5,3,4,6,7],hasOutsideLane:false}).status,'unobserved');
assert.equal(T.seatOpportunity({...args,order:[1,2,5,3,4,6,7],candidate:3}).status,'incompatible');
assert.equal(T.seatOpportunity({...args,order:[1,2,5,3,4,6,7],candidate:6}).status,'incompatible');
const head={events:12,opportunities:24},follower={events:5,opportunities:22};
const pair=T.effectiveSeparation(head,follower);
assert.equal(pair.status,'pair_heuristic');
assert.equal(pair.effective_n,24,'do not sum 46 as independent');
assert(pair.relative_signal>0);
const one=T.effectiveSeparation(head,null);
assert.equal(one.status,'single_side_heuristic');
assert.equal(T.effectiveSeparation(null,null).status,'unobserved');
const bef={events:5,opportunities:12},aft={events:6,opportunities:13};
const meta={sameRider:true,sameCounterDefinition:true,sameWindow:true,refreshConfirmed:true,
 interveningStarts:1,preStartSnapshot:true,postRaceSnapshot:true};
assert.deepEqual(T.exDeltaLabel({before:bef,after:aft,metadata:meta}).status,'candidate_only');
assert.equal(T.exDeltaLabel({before:bef,after:aft,metadata:{...meta,sameWindow:false}}).status,'unobserved');
assert.equal(T.exDeltaLabel({before:bef,after:{events:4,opportunities:11},metadata:meta}).status,'unobserved');
assert.equal(T.exDeltaLabel({before:bef,after:bef,metadata:{...meta,refreshConfirmed:false}}).status,'unobserved');
console.log('EX_TACTICAL_TRANSITION_GUARDS_OK '+JSON.stringify({line:[1,2,3,4],edges:3,
 noTeleport:true,contestDistinct:true,sourceLabelsNotGroundTruth:true,pairedEvidence:pair.status}));
